(ns shiftlefter.agent-doc.agent-md-gen
  "Generator for the repo-root `docs/AGENT.md` agent guide (sl-b06).

   `docs/AGENT.md` is a DERIVED artifact: a single fat file, single-sourced from
   the packaged `sl agent-doc` topics so it cannot drift from them. It ships
   nowhere (not the jar, not the release zip) — its only audience is someone
   reading the repo on GitHub or after a clone. Release/jar agents read the same
   doctrine through `sl agent-doc <topic>`; this file is the inlined view.

   Same single-source discipline as `builtins-gen`: `render` is a pure function
   of its `[{:topic :content}]` input so it is determinism- and drift-testable;
   `generate` loads the live packaged topic resources. Regenerate with
   `clojure -T:build gen-agent-md` (which chains `gen-builtins` first, since
   the `builtins` topic is itself generated — sl-hq30)."
  (:require [clojure.string :as str]
            [shiftlefter.agent-doc :as agent-doc]))

(def ^:private banner
  "The single H1 + a do-not-edit warning. Topic headings are demoted under this."
  (str "# AGENT.md — ShiftLefter agent guide\n"
       "\n"
       "> GENERATED — do not edit this file. It is single-sourced from the\n"
       "> packaged `sl agent-doc` topics in `resources/shiftlefter/agent_docs/`.\n"
       "> Edit a topic there and run `clojure -T:build gen-agent-md` (it\n"
       "> regenerates the `builtins` topic first via `gen-builtins`). With the\n"
       "> jar, read these same topics live with `sl agent-doc <topic>`.\n"))

(defn- demote-headings
  "Push every Markdown ATX heading down one level so topic titles sit under the
   single AGENT.md H1 (`# X` -> `## X`)."
  [content]
  (->> (str/split-lines content)
       (map (fn [line]
              (if (re-find #"^#+ " line)
                (str "#" line)
                line)))
       (str/join "\n")))

(defn- strip-read-next
  "Drop a trailing `Read next:` inter-topic nav block — it points at sibling
   `sl agent-doc` topics that are already inline here."
  [content]
  (let [lines (str/split-lines content)
        idx (->> lines
                 (keep-indexed (fn [i line]
                                 (when (re-find #"(?i)^read next:" line) i)))
                 first)]
    (if idx
      (-> (subvec (vec lines) 0 idx)
          (->> (str/join "\n"))
          str/trimr)
      content)))

(defn- render-topic
  [{:keys [content]}]
  (-> content strip-read-next demote-headings str/trim))

(defn render
  "Pure render of the derived AGENT.md from ordered `[{:topic :content}]` maps."
  [topics]
  (str banner
       "\n"
       (str/join "\n\n---\n\n" (map render-topic topics))
       "\n"))

(defn- load-topic-content
  [topic]
  (let [{:keys [status content]} (agent-doc/load-topic topic)]
    (if (= :ok status)
      content
      (throw (ex-info "agent-doc topic resource missing during AGENT.md generation"
                      {:topic topic :status status})))))

(defn generate
  "Load the live packaged topic resources in registry order and render."
  []
  (render
   (for [topic (agent-doc/topic-names)]
     {:topic topic :content (load-topic-content topic)})))

(defn render-standalone
  "Pure render of ONE topic as a standalone human page under docs/ (sl-d4pf):
   a pre-H1 GENERATED banner naming the source, then the source verbatim.
   docs/adoption.md is this projection of the `adoption` topic — one text,
   read by a human in docs/ and by anyone's agent from the jar."
  [topic content]
  (str "<!-- GENERATED — do not edit. Single-sourced from the packaged\n"
       "     `sl agent-doc " topic "` topic at " (agent-doc/topic-resource-path topic) "\n"
       "     under resources/. Edit the source, then run:\n"
       "     clojure -T:build gen-agent-md -->\n"
       "\n"
       content))

(defn generate-standalone
  "Load the live packaged `topic` resource and render it as a standalone page."
  [topic]
  (render-standalone topic (load-topic-content topic)))

(def standalone-pages
  "Topics that ALSO render as a standalone page under docs/ (sl-d4pf):
   topic -> path. The drift guard covers each entry like docs/AGENT.md."
  {"adoption" "docs/adoption.md"})

(defn write-doc!
  "Exec entry point: write the generated guide to `:out`, and every
   standalone projection in `standalone-pages` to its path.

   Invoked from the build via `clojure -X` so generation runs on the project
   classpath (the `-T:build` tool classpath does not see the framework)."
  [{:keys [out]}]
  (spit out (generate))
  (println (str "Wrote " out))
  (doseq [[topic path] standalone-pages]
    (spit path (generate-standalone topic))
    (println (str "Wrote " path))))
